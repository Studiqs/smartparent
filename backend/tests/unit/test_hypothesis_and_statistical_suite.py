class TestCryptographicAndSecurityIntegrity:
    """
    Verifies HMAC tampering protection and cryptographic audit trails.
    """

    @classmethod
    def setup_class(cls):
        cls.isolation_engine = DocumentAndIsolationEngine()
        cls.analytics_engine = AnalyticsAiEngine()

    def test_hmac_tamper_detection(self):
        """Tampering with signed URL path, signature, or expiry must fail verification."""
        path = "data/qp_pdfs/cbse_10_maths_sqp.pdf"
        signed = self.isolation_engine.generate_signed_url(
            resource_path=path,
            scope=SignedUrlScopeEnum.EXPERT_QUESTION_SET,
            expires_in_seconds=600,
        )

        # 1. Valid verification
        valid_res = self.isolation_engine.verify_signed_url(
            resource_path=path,
            signature=signed.signature,
            expires_at=signed.expires_at,
            scope="EXPERT_QUESTION_SET",
        )
        assert valid_res.is_valid is True

        # 2. Tampered path
        tampered_path = "data/qp_pdfs/cbse_10_maths_sqp_tampered.pdf"
        invalid_path_res = self.isolation_engine.verify_signed_url(
            resource_path=tampered_path,
            signature=signed.signature,
            expires_at=signed.expires_at,
            scope="EXPERT_QUESTION_SET",
        )
        assert invalid_path_res.is_valid is False

        # 3. Tampered signature (single-char flip)
        tampered_sig = ("0" if signed.signature[0] != "0" else "1") + signed.signature[1:]
        invalid_sig_res = self.isolation_engine.verify_signed_url(
            resource_path=path,
            signature=tampered_sig,
            expires_at=signed.expires_at,
            scope="EXPERT_QUESTION_SET",
        )
        assert invalid_sig_res.is_valid is False

    def test_cryptographic_provenance_hash_reproducibility(self):
        """Audit hash must be deterministic and change if any single score changes."""
        prov1 = self.analytics_engine.generate_expert_provenance(
            expert_id="exp-123",
            evaluation_id="eval-456",
            completion_date="2026-10-31",
            marks_awarded=9.0,
            total_max_marks=10.0,
            topic_node_ids=["CBSE_10_MATH_CH04"],
        )

        prov2 = self.analytics_engine.generate_expert_provenance(
            expert_id="exp-123",
            evaluation_id="eval-456",
            completion_date="2026-10-31",
            marks_awarded=9.0,
            total_max_marks=10.0,
            topic_node_ids=["CBSE_10_MATH_CH04"],
        )
        # Deterministic identical hash
        assert prov1.audit_hash == prov2.audit_hash

        # Single mark change creates completely different hash
        prov3 = self.analytics_engine.generate_expert_provenance(
            expert_id="exp-123",
            evaluation_id="eval-456",
            completion_date="2026-10-31",
            marks_awarded=9.5,  # 0.5 difference
            total_max_marks=10.0,
            topic_node_ids=["CBSE_10_MATH_CH04"],
        )
        assert prov1.audit_hash != prov3.audit_hash
